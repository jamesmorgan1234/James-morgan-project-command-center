import fs from 'node:fs';
import assert from 'node:assert/strict';
const manifest=JSON.parse(fs.readFileSync('manifest.webmanifest','utf8'));
const html=fs.readFileSync('index.html','utf8');
const sw=fs.readFileSync('service-worker.js','utf8');
const standard=fs.readFileSync('PWA_UPDATE_STANDARD.md','utf8');
assert.equal(manifest.id,'./'); assert.equal(manifest.start_url,'./'); assert.equal(manifest.scope,'./'); assert.equal(manifest.display,'standalone');
assert.equal(manifest.theme_color,'#000000'); assert.equal(manifest.background_color,'#000000');
const any=manifest.icons.find(x=>x.purpose==='any'); const mask=manifest.icons.find(x=>x.purpose==='maskable');
assert.equal(any?.src,'command-center-icon-v5.svg'); assert.equal(any?.type,'image/svg+xml');
assert.equal(mask?.src,'command-center-icon-v5-maskable.svg'); assert.equal(mask?.type,'image/svg+xml');
assert.notEqual(any?.src,mask?.src);
assert.match(html,/rel="manifest" href="\.\/manifest\.webmanifest\?v=3"/);
assert.match(sw,/james-command-center-v42/);
assert.ok(sw.includes("'./command-center-icon-v5.svg'")); assert.ok(sw.includes("'./command-center-icon-v5-maskable.svg'"));
assert.match(sw,/pathname\.endsWith\('\/manifest\.webmanifest'\)/); assert.match(sw,/pathname\.includes\('\/command-center-v5-'\)/); assert.match(sw,/fetch\(e\.request,\{cache:'no-store'\}\)/);
assert.match(standard,/Update Status: Not updatable/); assert.match(standard,/Future icon revisions must advance/); assert.match(standard,/command-center-icon-v5\.svg/);
console.log('PWA icon update pipeline QA passed.');
