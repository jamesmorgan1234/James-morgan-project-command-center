import fs from 'node:fs';
import assert from 'node:assert/strict';
const js=fs.readFileSync('project-roadmaps.js','utf8');
const css=fs.readFileSync('project-roadmaps.css','utf8');
const cfg=fs.readFileSync('app-config.js','utf8');
const sw=fs.readFileSync('service-worker.js','utf8');
assert.doesNotThrow(()=>new Function(js));
for(const category of ['Core Build','Automation','Integrations','Analytics','Security','Deployment','Agent Mode'])assert.ok(js.includes(category),`missing universal roadmap category ${category}`);
for(const special of ['Publishing','Commerce Operations','Content Engine','Service Operations'])assert.ok(js.includes(special),`missing specialized roadmap category ${special}`);
assert.match(js,/roadmap\.\$\{catKey\}\.\$\{phaseKey\}\.progress_percent/,'phase percentages must come from verified phase-specific metrics');
assert.match(js,/m\.verified&&m\.value_numeric/,'unverified roadmap metrics must not count');
assert.match(js,/Math\.round\(\(Number\(v\)\|\|0\)\/10\)\*10/,'project roadmap phase percentages must snap to 10% increments');
assert.match(js,/N\/A · Baseline pending/,'missing progress must display N/A instead of an invented percentage');
assert.match(js,/values\.every\(v=>v!==null\)/,'category percentage must derive only when every phase is verified');
assert.match(js,/ccProjectRoadmapCategory/,'open category must own a Back-history level');
assert.match(js,/openCategory===key/,'clicking the same roadmap category must toggle it closed');
assert.match(js,/dataset\.signature===sig/,'renderer must avoid self-triggered mutation loops');
assert.match(css,/cc-brain-card\[data-cc-brain-open\]\{display:none!important\}/,'duplicate Brain project card must stay hidden because Brain has its own home button');
assert.equal((css.match(/\{/g)||[]).length,(css.match(/\}/g)||[]).length,'project roadmap CSS braces must balance');
assert.match(cfg,/project-roadmaps\.js\?v=1/);assert.ok(sw.includes("'./project-roadmaps.js?v=1'"));
console.log('All-project category/phase roadmap QA passed.');
