import fs from 'node:fs';
import assert from 'node:assert/strict';
const css=fs.readFileSync('command-center-v6.css','utf8');
const js=fs.readFileSync('command-center-v6.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const cfg=fs.readFileSync('app-config.js','utf8');
const sw=fs.readFileSync('service-worker.js','utf8');
const manifest=JSON.parse(fs.readFileSync('manifest.webmanifest','utf8'));
assert.equal((css.match(/\{/g)||[]).length,(css.match(/\}/g)||[]).length,'V6 stylesheet braces must balance');
assert.match(cfg,/command-center-v6\.css\?v=1/); assert.match(cfg,/command-center-v6\.js\?v=1/);
assert.doesNotMatch(cfg,/command-center-v5\.js\?v=1/); assert.doesNotMatch(cfg,/command-center-v5-[1-6]\.css\?v=1/);
assert.match(html,/data-command-center-theme="v6"/); assert.match(html,/meta name="theme-color" content="#000000"/);
assert.match(html,/command-center-approved-icon-512\.png\?icon=6-ui/); assert.match(html,/manifest\.webmanifest\?v=6/);
assert.match(css,/#stats\{display:contents!important\}/,'home submenu must be able to visually insert beneath the clicked card without moving/removing the DOM shell');
assert.match(js,/const map = \{all:11,active:21,attention:31,earning:41\}/,'opened home menu must be ordered directly under its clicked tile');
assert.match(js,/openView = tile\.dataset\.view/);
assert.match(css,/project-view-grid[\s\S]*display:block!important/,'deep project detail must remain full width on mobile');
assert.match(js,/'private kpis'/); assert.match(js,/block\.dataset\.cc6Internal = 'hidden'/,'Private KPIs must stay in data/DOM but hidden from user UI');
assert.match(js,/Books in Series/); assert.match(css,/\.cc6-book-cover/); assert.match(css,/\.book-revenue-list\{display:flex!important/,'book titles/covers must render as a visible series strip');
assert.match(js,/hub-progress-head strong/,'project rings must derive from existing verified project progress display');
for(const label of ['Projects','Active / Live','Next Up','Projects Earning']) assert.match(js,new RegExp(label.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')));
assert.match(css,/stat-button\[data-view="revenue"\]\{display:none!important\}/,'Verified Revenue home tile stays removed');
assert.equal(manifest.icons[0]?.src,'command-center-approved-icon-512.png?icon=6-approved');
assert.match(sw,/james-command-center-v43/); assert.match(sw,/command-center-v6\.css\?v=1/); assert.match(sw,/command-center-v6\.js\?v=1/);
console.log('Command Center V6 exact-approved QA passed.');
