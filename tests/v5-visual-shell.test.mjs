import fs from 'node:fs';
import assert from 'node:assert/strict';
const cfg=fs.readFileSync('app-config.js','utf8');
const manifest=JSON.parse(fs.readFileSync('manifest.webmanifest','utf8'));
assert.doesNotMatch(cfg,/command-center-v5-[1-6]\.css\?v=1/,'legacy V5 CSS must not be loaded over the exact-approved shell');
assert.doesNotMatch(cfg,/command-center-v5\.js\?v=1/,'legacy V5 controller must not fight current theme/icon state');
assert.match(cfg,/command-center-v6\.css\?v=1/);
assert.match(cfg,/command-center-v6\.js\?v=1/);
assert.match(cfg,/command-center-v6-2\.css\?v=1/,'V6.2 exact visual hardening remains the visual foundation');
assert.doesNotMatch(cfg,/command-center-v6-2\.js\?v=1/,'duplicate V6.2 mutation observer is intentionally retired to reduce glitching');
assert.match(cfg,/command-center-v7\.css\?v=1/,'V7 user-requested polish must load');
assert.match(cfg,/command-center-v7\.js\?v=1/,'V7 stable controller must load');
assert.ok(cfg.indexOf('command-center-v6-2.css?v=1')>cfg.indexOf('command-center-v6.css?v=1'),'V6.2 CSS must load after base V6 CSS');
assert.ok(cfg.indexOf('command-center-v7.css?v=1')>cfg.indexOf('command-center-v6-2.css?v=1'),'V7 CSS must load last');
assert.ok(cfg.indexOf('command-center-v7.js?v=1')>cfg.indexOf('command-center-v6.js?v=1'),'V7 JS must load after V6 controller');
assert.equal(manifest.theme_color,'#000000');
assert.equal(manifest.icons[0]?.src,'command-center-approved-icon-192.png?icon=7-any-192');
assert.equal(manifest.icons[2]?.purpose,'maskable');
console.log('V5 retirement / V7 migration QA passed.');
